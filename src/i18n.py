LABEL_MAP = {
    "120M": ("2 hours", "2 horas"),
    "60M": ("1 hour", "1 hora"),
    "15M": ("15 minutes", "15 minutos"),
}


def t(user_lang: str | None, key: str, **kwargs) -> str:
    lang = user_lang if user_lang in STRINGS else "en"
    text = STRINGS[lang].get(key, STRINGS["en"].get(key, key))
    if kwargs:
        text = text.format(**kwargs)
    return text


def reminder_label(notif_type: str, lang: str) -> str:
    idx = 0 if lang == "en" else 1
    return LABEL_MAP.get(notif_type, ("", ""))[idx]
